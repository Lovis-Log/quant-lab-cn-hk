def recovery_return(drawdown: float) -> float:
    if not math.isfinite(drawdown) or not -1 < drawdown <= 0:
        raise ValueError("回撤必须是 −100% 与 0% 之间的有限值。")
    return 1 / (1 + drawdown) - 1


def interpret(topic: str, value: float | None = None, *, observations=None, period="所选样本区间") -> str:
    item = KNOWLEDGE[topic]
    if value is None or not math.isfinite(value):
        return "当前没有足够的有效计算值（未加载、样本不足或分母接近零）。请查看页面的数据与样本说明；这里不推断结果。"
    reading = f"{value:+.2%}" if item.percent else f"{value:.4f}"
    text = f"程序在{period}计算值为 {reading}。"
    if observations is not None:
        text += f"价格/净值观测数为 {observations}。"
    if topic == "drawdown":
        text += f"相对该区间此前峰值，最深下跌约 {abs(value):.2%}。"
        if -1 < value <= 0:
            text += f"从这个低点恢复到对应峰值需要上涨约 {recovery_return(value):.2%}；这不说明恢复时间。"
    elif topic in {"volatility", "sharpe"}:
        text += "采用样本日收益与 252 个交易日的年化近似；短样本结果不稳定。"
    elif topic == "variance":
        text += "收益率以小数计算，方差单位是收益率的平方，不直接读成百分比。"
    elif topic == "simple_return":
        text += "这是首尾价格变化；不自动包含现金分红或交易成本。"
    elif topic == "correlation":
        text += "它描述该对齐样本的线性关系，不证明因果或未来关系。"
    return text
